import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const GENERATED_DIR = "src/generated";
const HEADER = "// @ts-nocheck -- generated by ANTLR, see npm run antlr\n";

const files = await readdir(GENERATED_DIR);

for (const file of files.filter((f) => f.endsWith(".ts"))) {
  const path = join(GENERATED_DIR, file);
  const source = await readFile(path, "utf8");

  if (!source.startsWith(HEADER)) {
    await writeFile(path, HEADER + source);
  }
}

console.log(`postprocessed ${files.length} file(s) in ${GENERATED_DIR}`);
